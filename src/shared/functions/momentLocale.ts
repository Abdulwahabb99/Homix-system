import moment from "moment";
import "moment/locale/ar";

/**
 * تسجيل اللغة العربية في moment للاستخدام الصريح فقط عبر `.locale("ar")`
 * (تقويم نطاق التاريخ، عرض تواريخ الشحنات… إلخ)، مع إبقاء الإنجليزية هي
 * الافتراضية العامة.
 *
 * سبب ذلك: مجرد استيراد `moment/locale/ar` يستدعي `defineLocale` الذي يجعل
 * العربية هي اللغة العامة كأثر جانبي، فتتحوّل كل صيغ `moment().format(...)`
 * لأرقام هندية — ما يكسر تواريخ الـ API و`new Date(...)` والحقول الأصلية.
 * لذا نعيد الافتراضي فوراً إلى الإنجليزية.
 *
 * استورد هذا الملف بدل `moment/locale/ar` مباشرةً في أي مكان يحتاج العربية.
 */
moment.locale("en");

export default moment;
